"""Refuse game-derived content before it reaches the repository or a release.

Policy: project-brief.md section 9 and architecture.md section 14. Run with ``python3 -I``.

Modes (pick one):
  --staged            files staged in git (pre-commit hook)
  --tree              every tracked file (CI)
  --archive PATH      members of a release archive (.zip, .tar, .tar.gz, .tar.zst)
  PATH ...            explicit files or directories
  --deep              also compare against the local boot ELF and overlays in baserom/raw (contributors only)
  --release           the files are a release tree (an install, an unpacked AppImage): host executables and
                      libraries (ELF or PE, never MIPS) and copies of allowlisted files are allowed at any size

Published function maps (data/maps/<profile>/<unit>.toml, share/dq8/maps/... in a release) must hold exactly
the format of Docs/formats/function-map.md: addresses, sizes, counts and kernel/SDK names, no table entries, no
comments and no other text.

Exit status 1 and one line per finding when anything is refused; 0 when clean.
"""
from __future__ import annotations

import argparse
import hashlib
import math
import os
import re
import subprocess
import sys
import tarfile
import tomllib
import zipfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Names exactly as they appear on the disc or in emulator/tool output. Case-insensitive.
FORBIDDEN_NAME = re.compile(
    r"(\.(iso|7z|cso|chd|elf|irx|img|mvi|dat|hd6|bin|gs|p2s|gsdump)$)"
    r"|(^(slus|sles|slpm|slps|scus|sces|scps|sled|slka)[_-])"
    r"|(^system\.cnf$)|(^ioprp.*\.img$)|(^dmydata$)|(\.gs\.(zst|xz|gz)$)",
    re.IGNORECASE,
)
FORBIDDEN_DIR = re.compile(r"^(Game|baserom|generated|work)(/|$)")
ALLOWLIST_FILE = ROOT / ".no-game-data-allow"  # one glob per line, for first-party binaries (icons, fonts)
MAX_SIZE = 1024 * 1024
ENTROPY_MIN_SIZE = 32 * 1024
ENTROPY_LIMIT = 7.0
# --deep ignores low-diversity windows (runs of '=', '-', spaces, zeros): they occur in any text file and in the
# boot ELF alike and identify nothing.
MIN_WINDOW_DISTINCT = 8
TEXT_RULES = [
    ("hex-run", re.compile(r"(?:\b[0-9A-Fa-f]{2}\b[ ,]){16,}")),
    ("escaped-bytes", re.compile(r"(?:\\x[0-9A-Fa-f]{2}){16,}")),
    ("byte-literals", re.compile(r"0x[0-9A-Fa-f]{2}(?:\s*,\s*0x[0-9A-Fa-f]{2}){15,}")),
    ("xxd-dump", re.compile(r"(?:^[0-9A-Fa-f]{7,8}:(?: [0-9A-Fa-f]{4}){4,}.*\n){4,}", re.MULTILINE)),
    ("base64-run", re.compile(r"[A-Za-z0-9+/]{256,}={0,2}")),
    # Banners of recompiler output. Spelled in pieces so this file does not match its own rule.
    ("generated-code", re.compile("|".join([r"Generated by Export" + r"PS2Functions",
                                            r"ps2_stubs::" + r"TODO_NAMED",
                                            r"Generated by ps2x?" + r"Recomp"]), re.IGNORECASE)),
]
HASH_RE = re.compile(r"\b(sha1|crc32)\s*=\s*\"([0-9a-fA-F]{8,40})\"")
# Region profiles are named by disc serial (architecture.md §13.4) and hold only names, sizes and hashes; an
# install carries them under share/dq8/regions.
REGION_PROFILE = re.compile(r"(?:^|/)(?:data|share/dq8)/regions/[^/]+\.toml$")
PUBLISHED_MAP = re.compile(r"(?:^|/)(?:data|share/dq8)/maps/([^/]+)/([^/]+)\.toml$")
CALL_LIST = ROOT / "include" / "dq8" / "abi" / "ps2recomp" / "ps2_call_list.h"
MAP_KEYS = {"format", "profile", "unit", "source_sha1", "code", "functions", "link_return_entries", "named",
            "jump_table"}
MAP_REQUIRED = {"format", "profile", "unit", "source_sha1", "code", "functions"}
ELF_MACHINE_MIPS = 8


def git_files(args: list[str]) -> list[str]:
    out = subprocess.run(["git", "-C", str(ROOT), *args, "-z"], check=True, capture_output=True).stdout
    return [p for p in out.decode("utf-8", "surrogateescape").split("\0") if p]


def load_allowlist() -> list[str]:
    if not ALLOWLIST_FILE.is_file():
        return []
    return [l.strip() for l in ALLOWLIST_FILE.read_text().splitlines() if l.strip() and not l.startswith("#")]


def allowed(rel: str, allowlist: list[str]) -> bool:
    from fnmatch import fnmatch
    return any(fnmatch(rel, pat) for pat in allowlist)


def known_hashes() -> set[str]:
    found: set[str] = set()
    for toml in (ROOT / "data" / "regions").glob("*.toml"):
        for _, value in HASH_RE.findall(toml.read_text(encoding="utf-8", errors="replace")):
            found.add(value.lower())
    return found


def call_list_names(path: Path = CALL_LIST) -> tuple[set[str], set[str]]:
    """The kernel-call and library-stub names of the runtime's call list (the names a published map may keep)."""
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    out = []
    for macro in ("PS2_SYSCALL_LIST", "PS2_STUB_LIST"):
        m = re.search(r"#define\s+" + macro + r"\(X\)((?:.*\\\n)*.*)", text)
        out.append(set(re.findall(r"\bX\((\w+)\)", m.group(1))) if m else set())
    return out[0], out[1]


def resolves(name: str, entries: set[str]) -> bool:
    """The recompiler's lookup: an exact match, else one leading underscore removed or added."""
    if name in entries:
        return True
    return name[1:] in entries if name.startswith("_") else "_" + name in entries


def published_map_problems(rel_path: str, data: bytes, names: tuple[set[str], set[str]]) -> list[str]:
    """Why a file under data/maps/ is not a published map in the format (empty when it is)."""
    m = PUBLISHED_MAP.search(rel_path)
    if not m:
        return ["not <profile>/<unit>.toml under maps/"]
    if b"#" in data:
        return ["comments are not allowed"]
    try:
        doc = tomllib.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, tomllib.TOMLDecodeError) as e:
        return [f"not TOML: {e}"]
    problems: list[str] = []
    unknown = set(doc) - MAP_KEYS
    if unknown:
        problems.append(f"keys outside the format: {sorted(unknown)}")
    missing = MAP_REQUIRED - set(doc)
    if missing:
        return problems + [f"missing keys: {sorted(missing)}"]

    def u32(v: object) -> bool:
        return type(v) is int and 0 <= v <= 0xFFFFFFFF

    if doc["format"] != 1 or type(doc["format"]) is not int:
        problems.append("format must be 1")
    if doc["profile"] != m.group(1) or not re.fullmatch(r"[A-Z0-9_]+", str(doc["profile"])):
        problems.append("profile does not match its directory")
    if doc["unit"] != m.group(2) or not re.fullmatch(r"[a-z0-9_]+", str(doc["unit"])):
        problems.append("unit does not match its file name")
    if not isinstance(doc["source_sha1"], str) or not re.fullmatch(r"[0-9a-f]{40}", doc["source_sha1"]):
        problems.append("source_sha1 must be 40 lower-case hex digits")
    code = doc["code"]
    if not (isinstance(code, list) and len(code) == 2 and all(u32(v) for v in code) and code[0] < code[1]):
        return problems + ["code must be [start, end] with start < end"]
    inside = lambda a: code[0] <= a < code[1]  # noqa: E731
    starts: set[int] = set()
    prev_end = -1
    functions = doc["functions"]
    if not isinstance(functions, list):
        return problems + ["functions must be an array"]
    for f in functions:
        if not (isinstance(f, list) and len(f) == 2 and all(u32(v) for v in f)):
            problems.append(f"function {f!r} is not [start, size]")
            break
        start, size = f
        if size == 0 or start % 4 or size % 4 or not inside(start) or start + size > code[1] or start < prev_end:
            problems.append(f"function [{start:#010x}, {size:#x}] is empty, misaligned, unsorted, overlapping "
                            "or outside code")
            break
        starts.add(start)
        prev_end = start + size
    entries = doc.get("link_return_entries", [])
    if not isinstance(entries, list) or not all(u32(a) and a % 4 == 0 and inside(a) for a in entries):
        problems.append("link_return_entries must be 4-aligned addresses inside code")
    named = doc.get("named", [])
    if not isinstance(named, list):
        problems.append("named must be an array of tables")
        named = []
    for row in named:
        if not isinstance(row, dict) or set(row) != {"start", "name"}:
            problems.append("each [[named]] has exactly start and name")
            break
        if not u32(row["start"]) or row["start"] not in starts:
            problems.append("a [[named]] start is no function's start")
            break
        name = row["name"]
        if not (isinstance(name, str) and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name)
                and (resolves(name, names[0]) or resolves(name, names[1]))):
            problems.append(f"[[named]] name {name!r} is not a kernel or SDK name of the runtime's call list")
            break
    tables = doc.get("jump_table", [])
    if not isinstance(tables, list):
        problems.append("jump_table must be an array of tables")
        tables = []
    for row in tables:
        if not isinstance(row, dict):
            problems.append("each [[jump_table]] must be a table")
            break
        if "entries" in row:
            problems.append("a [[jump_table]] holds entries (they are read from the user's disc)")
            break
        if set(row) != {"address", "base_register", "count"}:
            problems.append("each [[jump_table]] has exactly address, base_register and count")
            break
        if not (u32(row["address"]) and row["address"] and row["address"] % 4 == 0
                and type(row["base_register"]) is int and 0 <= row["base_register"] <= 31
                and type(row["count"]) is int and row["count"] >= 1):
            problems.append("a [[jump_table]] has a zero or misaligned address, a bad register or count")
            break
    return problems


def host_binary(data: bytes) -> bool:
    """An ELF for anything but MIPS (the game's code is MIPS), or a PE file: what a release tree is built of."""
    if data[:4] == b"\x7fELF" and len(data) >= 20:
        machine = int.from_bytes(data[18:20], "little" if data[5] == 1 else "big")
        return machine != ELF_MACHINE_MIPS
    return data[:2] == b"MZ"


def entropy(data: bytes) -> float:
    if not data:
        return 0.0
    counts = [0] * 256
    for b in data:
        counts[b] += 1
    n = len(data)
    return -sum((c / n) * math.log2(c / n) for c in counts if c)


class Checker:
    def __init__(self, deep: bool, release: bool = False) -> None:
        self.findings: list[str] = []
        self.allowlist = load_allowlist()
        self.hashes = known_hashes()
        self.windows: set[bytes] = set()
        self.release = release
        self.call_names = call_list_names()
        # In a release tree, copies of allowlisted tracked files (icons, fonts) keep their permission.
        self.allowed_sha1: set[str] = set()
        if release and self.allowlist:
            for rel in git_files(["ls-files"]):
                if allowed(rel, self.allowlist) and (ROOT / rel).is_file():
                    self.allowed_sha1.add(hashlib.sha1((ROOT / rel).read_bytes()).hexdigest())
        if deep:
            self._index_local_disc_files()

    def _index_local_disc_files(self) -> None:
        raw = ROOT / "baserom" / "raw"
        sources = [raw / "SLUS_212.07", *sorted((raw / "BIN").glob("*.BIN"))] if raw.is_dir() else []
        for src in sources:
            if src.is_file():
                data = src.read_bytes()
                for off in range(0, len(data) - 32, 16):
                    window = data[off : off + 32]
                    if len(set(window)) >= MIN_WINDOW_DISTINCT:
                        self.windows.add(window)
        if not self.windows:
            print("note: --deep found no baserom/raw inputs; skipping byte-window comparison", file=sys.stderr)

    def refuse(self, rel: str, rule: str, detail: str = "") -> None:
        self.findings.append(f"{rel}: {rule}{(' (' + detail + ')') if detail else ''}")

    def check(self, rel: str, data: bytes) -> None:
        rel = rel.replace(os.sep, "/")
        if allowed(rel, self.allowlist):
            return
        name = rel.rsplit("/", 1)[-1]
        path = rel.split(":", 1)[-1]  # an archive member's path inside the archive
        if FORBIDDEN_DIR.match(rel):
            self.refuse(rel, "forbidden-directory")
        is_region_profile = REGION_PROFILE.search(path) is not None
        if FORBIDDEN_NAME.search(name) and not is_region_profile:
            self.refuse(rel, "forbidden-name")
        if self.hashes:
            sha1 = hashlib.sha1(data).hexdigest()
            crc = f"{zlib.crc32(data) & 0xFFFFFFFF:08x}"
            if sha1 in self.hashes or crc in self.hashes:
                self.refuse(rel, "known-game-file-hash")
        if re.search(r"(?:^|/)(?:data|share/dq8)/maps/", path) and path.endswith(".toml"):
            for problem in published_map_problems(path, data, self.call_names):
                self.refuse(rel, "published-map", problem)
        release_binary = self.release and (host_binary(data) or hashlib.sha1(data).hexdigest() in self.allowed_sha1)
        if len(data) > MAX_SIZE and not release_binary:
            self.refuse(rel, "too-large", f"{len(data)} bytes > {MAX_SIZE}")
        is_binary = b"\0" in data[:8192]
        if is_binary:
            # A release's host executables and libraries pass here; the hash and --deep window checks still apply.
            if not release_binary:
                self.refuse(rel, "binary-file", "allowlist first-party binaries in .no-game-data-allow")
                if len(data) >= ENTROPY_MIN_SIZE and entropy(data) > ENTROPY_LIMIT:
                    self.refuse(rel, "high-entropy", f"{entropy(data):.2f} bits/byte")
        else:
            text = data.decode("utf-8", "replace")
            for rule, rx in TEXT_RULES:
                m = rx.search(text)
                if m:
                    line = text.count("\n", 0, m.start()) + 1
                    self.refuse(rel, rule, f"line {line}")
        if self.windows and len(data) >= 47:
            for off in range(0, len(data) - 32):
                window = data[off : off + 32]
                if window in self.windows and len(set(window)) >= MIN_WINDOW_DISTINCT:
                    self.refuse(rel, "bytes-from-disc", f"offset {off}")
                    break

    def check_path(self, rel: str, path: Path) -> None:
        if path.is_symlink() or not path.is_file():
            return
        self.check(rel, path.read_bytes())

    def check_archive(self, archive: Path) -> None:
        if zipfile.is_zipfile(archive):
            with zipfile.ZipFile(archive) as zf:
                for info in zf.infolist():
                    if not info.is_dir():
                        self.check(f"{archive.name}:{info.filename}", zf.read(info))
            return
        with tarfile.open(archive) as tf:
            for member in tf.getmembers():
                if member.isfile():
                    fh = tf.extractfile(member)
                    if fh is not None:
                        self.check(f"{archive.name}:{member.name}", fh.read())

    def check_gitignore(self) -> None:
        probes = ["Game/x.iso", "baserom/raw/SLUS_212.07", "generated/a.cpp", "work/x", "a.iso", "SLUS_212.07",
                  "BIN/TITLE.BIN", "MODULES/PADMAN.IRX", "DATA.HD6", "x.gs", "tools/local.env"]
        r = subprocess.run(["git", "-C", str(ROOT), "check-ignore", "-q", "--stdin"], input="\n".join(probes),
                           text=True, capture_output=True)
        # check-ignore -q with --stdin exits 0 if *any* path is ignored; verify each individually instead.
        for probe in probes:
            r = subprocess.run(["git", "-C", str(ROOT), "check-ignore", "-q", probe], capture_output=True)
            if r.returncode != 0:
                self.refuse(".gitignore", "gitignore-gap", f"{probe} is not ignored")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--staged", action="store_true")
    ap.add_argument("--tree", action="store_true")
    ap.add_argument("--archive", action="append", default=[])
    ap.add_argument("--deep", action="store_true")
    ap.add_argument("--release", action="store_true")
    ap.add_argument("paths", nargs="*")
    args = ap.parse_args(argv)

    checker = Checker(deep=args.deep, release=args.release)
    if args.staged:
        for rel in git_files(["diff", "--cached", "--name-only", "--diff-filter=ACMR"]):
            checker.check_path(rel, ROOT / rel)
    if args.tree:
        for rel in git_files(["ls-files"]):
            if rel.startswith("third_party/"):
                continue  # submodules: their own content, scanned by their own projects
            checker.check_path(rel, ROOT / rel)
        checker.check_gitignore()
    for archive in args.archive:
        checker.check_archive(Path(archive))
    for p in args.paths:
        path = Path(p)
        if path.is_dir():
            for f in sorted(path.rglob("*")):
                if f.is_file():
                    checker.check_path(str(f.relative_to(ROOT) if f.is_relative_to(ROOT) else f), f)
        else:
            checker.check_path(str(path.relative_to(ROOT) if path.is_relative_to(ROOT) else path), path)

    if checker.findings:
        print("no-game-data: REFUSED", file=sys.stderr)
        for line in checker.findings:
            print("  " + line, file=sys.stderr)
        return 1
    print("no-game-data: clean")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
